// Converts snarkjs artifacts into Gno source: the verifying key, and the
// proof/public-signal vectors used by the Gno test suite.
//
// Usage: node gen-vkey.mjs [--g2-real-first]
import fs from "node:fs";

const FP = 32n;
const MOD = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;
const g2RealFirst = process.argv.includes("--g2-real-first");

const be = (dec) => {
  let v = BigInt(dec) % MOD;
  const out = Buffer.alloc(Number(FP));
  for (let i = Number(FP) - 1; i >= 0; i--) {
    out[i] = Number(v & 0xffn);
    v >>= 8n;
  }
  return out;
};
const hex = (buf) => "0x" + buf.toString("hex");

function goBytes(buf, indent = "\t") {
  const parts = [];
  for (const b of buf) parts.push("0x" + b.toString(16).padStart(2, "0"));
  const lines = [];
  for (let i = 0; i < parts.length; i += 8) lines.push(indent + parts.slice(i, i + 8).join(", ") + ",");
  return lines.join("\n");
}
function decl(name, buf, doc = "") {
  return `${doc}var ${name} = []byte{\n${goBytes(buf)}\n}\n`;
}

// G1 affine [x, y] -> 64 bytes
const g1 = (p) => Buffer.concat([be(p[0]), be(p[1])]);
// G2 [[x0,x1],[y0,y1]] -> 128 bytes, EVM order (imaginary part first by default)
function g2(p) {
  const xs = g2RealFirst ? [p[0][0], p[0][1]] : [p[0][1], p[0][0]];
  const ys = g2RealFirst ? [p[1][0], p[1][1]] : [p[1][1], p[1][0]];
  return Buffer.concat([be(xs[0]), be(xs[1]), be(ys[0]), be(ys[1])]);
}

const vk = JSON.parse(fs.readFileSync("vkey.json", "utf8"));
const ic = vk.IC.map(g1);

let src = `// Code generated by circuits/gen-vkey.mjs from a snarkjs verification key.
// DO NOT EDIT. Regenerate after changing the circuit or the ceremony.
package groth16

// NPublic is the number of public signals the circuit exposes.
const NPublic = ${vk.nPublic}

`;

// snarkjs numbers G2 as [[x_c0, x_c1], [y_c0, y_c1]]; encode as the precompile expects.
src += decl("vkAlpha1", g1(vk.vk_alpha_1), "");
src += decl("vkBeta2", g2(vk.vk_beta_2), "");
src += decl("vkGamma2", g2(vk.vk_gamma_2), "");
src += decl("vkDelta2", g2(vk.vk_delta_2), "");
src += "var vkIC = [][]byte{\n" + ic.map((b) => "{\n" + goBytes(b, "\t\t") + "\n\t},").join("\n") + "\n}\n";

fs.writeFileSync("../gno.land/p/curtain/groth16/vkey.gno", src);

// Test vectors: every real proof on disk, as hex, for the Go test suites.
const fx = JSON.parse(fs.readFileSync("fixtures.json", "utf8"));
const proofs = fs
  .readdirSync(".")
  .filter((f) => /^proof-.*\.json$/.test(f))
  .sort()
  .map((f) => {
    const tag = f.slice("proof-".length, -".json".length);
    const proof = JSON.parse(fs.readFileSync(f, "utf8"));
    const pub = JSON.parse(fs.readFileSync(`public-${tag}.json`, "utf8"));
    return {
      tag,
      A: hex(g1([proof.pi_a[0], proof.pi_a[1]])).slice(2),
      B: hex(g2([proof.pi_b[0], proof.pi_b[1]])).slice(2),
      C: hex(g1([proof.pi_c[0], proof.pi_c[1]])).slice(2),
      vote: pub[0],
      pollId: pub[1],
      root: pub[2],
      nullifier: pub[3],
    };
  });

if (proofs.length) {
  const first = proofs[0];
  const pkgFixture = `package groth16

var testProofA = []byte{
${goBytes(Buffer.from(first.A, "hex"))}
}

var testProofB = []byte{
${goBytes(Buffer.from(first.B, "hex"))}
}

var testProofC = []byte{
${goBytes(Buffer.from(first.C, "hex"))}
}

var testPublicSignals = [][]byte{
${[first.vote, first.pollId, first.root, first.nullifier]
  .map((v) => "{\n" + goBytes(be(v), "\t\t") + "\n\t},")
  .join("\n")}
}
`;
  fs.writeFileSync("../gno.land/p/curtain/groth16/zz_fixtures_test.gno", pkgFixture);

  const realmFixture = `// Code generated by circuits/gen-vkey.mjs. Real Groth16 artifacts.
package curtain

const testRoot = "${hex(be(fx.root)).slice(2)}"

type testBallot struct {
	Tag        string
	ProofA     string
	ProofB     string
	ProofC     string
	Vote       int
	PollId     int
	Root       string
	Nullifier  string
}

var testBallots = []testBallot{
${proofs
  .map(
    (p) => `	{
		Tag:       "${p.tag}",
		ProofA:    "${p.A}",
		ProofB:    "${p.B}",
		ProofC:    "${p.C}",
		Vote:      ${p.vote},
		PollId:    ${p.pollId},
		Root:      "${hex(be(p.root)).slice(2)}",
		Nullifier: "${hex(be(p.nullifier)).slice(2)}",
	},`,
  )
  .join("\n")}
}
`;
  fs.writeFileSync("../gno.land/r/curtain/zz_fixtures_test.gno", realmFixture);
  console.log("proofs embedded:", proofs.map((p) => p.tag).join(", "));
}
console.log("wrote vkey.gno, g2RealFirst =", g2RealFirst);
